"""Durable operations and their local actor runtime.

An `Operation` is a persisted checkpoint: its `State` is the per-type state
struct encoded with `gojson`, byte-identical to the Go implementation. Each
type advances through `Step`s, which carry the next checkpoint and the
primitives to dispatch. `LocalOperationManager` runs operations on local
primitives and routes `remote_job` operations to `RemoteJobHandler`s.
"""

